def _normal_family(variance: float) -> DGLMFamily:
    """Known-variance normal family built through the public contract.

    West, Harrison & Migon (1985, sec. 2.2) prove the DGLM step with a
    normal observation and identity link reduces exactly to the Kalman
    step: a normal is determined by its two moments, and the exact
    conditional mean is linear, so both approximations vanish.
    """

    def match_moments(forecast_mean, forecast_variance):
        return forecast_mean, forecast_variance

    def log_forecast(emission, mean, var):
        return jstats.norm.logpdf(
            emission, loc=mean, scale=jnp.sqrt(var + variance)
        )

    def update(emission, mean, var):
        gain = var / (var + variance)
        return mean + gain * (emission - mean), var * variance / (
            var + variance
        )

    def posterior_moments(mean, var):
        return mean, var

    return DGLMFamily(
        match_moments=match_moments,
        log_forecast=log_forecast,
        update=update,
        posterior_moments=posterior_moments,
    )


def _trend_model():
    """Locally linear trend used across the tests."""
    transition = jnp.array([[1.0, 1.0], [0.0, 1.0]])
    observation = jnp.array([1.0, 0.0])
    initial_mean = jnp.array([0.3, 0.1])
    initial_cov = jnp.array([[0.5, 0.1], [0.1, 0.2]])
    evolution = jnp.diag(jnp.array([0.05, 0.01]))
    return transition, observation, initial_mean, initial_cov, evolution


