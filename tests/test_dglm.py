class TestBinomialFamily:
    """Beta moment matching, conjugate algebra, and the trials knob."""

    @pytest.mark.parametrize("q", [0.01, 0.5, 4.0])
    @pytest.mark.parametrize("f", [-1.5, 0.0, 2.0])
    def test_beta_match_solves_moment_equations(self, f, q):
        family = binomial(trials=5)
        alpha, beta = (
            jnp.asarray(value)
            for value in family.match_moments(jnp.asarray(f), jnp.asarray(q))
        )
        eps = float(jnp.finfo(alpha.dtype).eps)
        np.testing.assert_allclose(
            np.asarray(digamma(alpha) - digamma(beta)), f, atol=1e4 * eps
        )
        np.testing.assert_allclose(
            np.asarray(polygamma(1, alpha) + polygamma(1, beta)),
            q,
            rtol=1e4 * eps,
        )

    def test_conjugate_update_algebra(self):
        family = binomial(trials=5)
        alpha, beta = family.update(
            jnp.asarray(3.0), jnp.asarray(2.0), jnp.asarray(4.0)
        )
        np.testing.assert_allclose(np.asarray(alpha), 5.0)
        np.testing.assert_allclose(np.asarray(beta), 6.0)

    def test_binomial_single_trial_equals_bernoulli(self):
        emissions = jnp.array([1, 0, 1, 1])
        common = dict(
            transition_covariance=jnp.array([[0.05]]),
        )
        one = dglm_filter(
            jnp.array([0.2]),
            jnp.array([[0.4]]),
            jnp.eye(1),
            jnp.ones(1),
            emissions,
            family=binomial(trials=1),
            **common,
        )
        bern = dglm_filter(
            jnp.array([0.2]),
            jnp.array([[0.4]]),
            jnp.eye(1),
            jnp.ones(1),
            emissions,
            family=bernoulli(),
            **common,
        )
        np.testing.assert_allclose(
            one.filtered_means, bern.filtered_means, rtol=1e-14
        )
        np.testing.assert_allclose(
            one.marginal_loglik, bern.marginal_loglik, rtol=1e-14
        )

    def test_rejects_nonpositive_trials(self):
        with pytest.raises(ValueError, match="positive integer"):
            binomial(trials=0)


class TestDispersionDiscount:
    """Berry and West's random-effects discount rho."""

    def _run(self, **kwargs):
        transition, observation, mean_0, cov_0, evolution = _trend_model()
        return dglm_filter(
            mean_0,
            cov_0,
            transition,
            observation,
            jnp.array([1, 0, 3]),
            family=poisson(),
            transition_covariance=evolution,
            **kwargs,
        )

    def test_unit_dispersion_is_a_no_op(self):
        default = self._run()
        explicit = self._run(dispersion_discount=1.0)
        np.testing.assert_array_equal(
            np.asarray(default.filtered_means),
            np.asarray(explicit.filtered_means),
        )
        np.testing.assert_array_equal(
            np.asarray(default.marginal_loglik),
            np.asarray(explicit.marginal_loglik),
        )

    def test_dispersion_inflates_matched_prior(self):
        # First step: f = F'm0, q = (F'C0F)/rho before matching.
        _, observation, mean_0, cov_0, _ = _trend_model()
        rho = 0.5
        posterior = self._run(dispersion_discount=rho)
        f = float(observation @ mean_0)
        q = float(observation @ cov_0 @ observation) / rho
        alpha, beta = poisson().match_moments(jnp.asarray(f), jnp.asarray(q))
        eps = float(jnp.finfo(posterior.conjugate_alphas.dtype).eps)
        np.testing.assert_allclose(
            float(posterior.conjugate_alphas[0]),
            float(jnp.asarray(alpha)) + 1.0,
            rtol=1e3 * eps,
        )
        np.testing.assert_allclose(
            float(posterior.conjugate_betas[0]),
            float(jnp.asarray(beta)) + 1.0,
            rtol=1e3 * eps,
        )

    @pytest.mark.parametrize("bad", [0.0, 1.5, -0.2])
    def test_rejects_dispersion_outside_unit_interval(self, bad):
        with pytest.raises(ValueError):
            self._run(dispersion_discount=bad)


class TestMomentMatching:
    """The exact digamma/trigamma match and its closed-form limit."""

    @pytest.mark.parametrize("q", [1e-4, 0.01, 0.5, 4.0, 20.0])
    def test_poisson_match_solves_moment_equations(self, q):
        family = poisson()
        f = 0.7
        alpha, beta = (
            jnp.asarray(value)
            for value in family.match_moments(jnp.asarray(f), jnp.asarray(q))
        )
        eps = float(jnp.finfo(alpha.dtype).eps)
        np.testing.assert_allclose(
            np.asarray(polygamma(1, alpha)), q, rtol=1e3 * eps
        )
        np.testing.assert_allclose(
            np.asarray(digamma(alpha) - jnp.log(beta)), f, atol=1e3 * eps
        )

    def test_small_q_limit_recovers_whm_closed_form(self):
        # WHM (1985, sec. 5): mode/curvature matching gives
        # alpha = 1/q, beta = exp(-f)/q — the q -> 0 limit of the
        # exact match (trigamma(a) = 1/a + 1/(2a^2) + O(a^-3)).
        family = poisson()
        f, q = -0.4, 1e-6
        alpha, beta = (
            jnp.asarray(value)
            for value in family.match_moments(jnp.asarray(f), jnp.asarray(q))
        )
        np.testing.assert_allclose(np.asarray(alpha * q), 1.0, rtol=1e-5)
        np.testing.assert_allclose(
            np.asarray(beta * q * jnp.exp(f)), 1.0, rtol=1e-5
        )


